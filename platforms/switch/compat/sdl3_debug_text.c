/*
 * sdl3_debug_text.c — a real implementation of SDL3's SDL_RenderDebugText for
 * the Switch (switch-sdl2 has no equivalent; the shim used to stub it to a
 * no-op, which is why the in-game settings overlay drew an empty box).
 *
 * Draws an 8x8 bitmap font (the public-domain font8x8_basic by Daniel Hepper,
 * https://github.com/dhepper/font8x8) one set pixel at a time via
 * SDL_RenderFillRect, so it inherits the renderer's CURRENT draw colour — which
 * is exactly how the SDL3 original behaves and how port_debug_menu.cpp drives it
 * (it sets the colour per line before each call).
 *
 * Compiled as plain C and linked in via the Makefile's SWITCH_SRCS. Included
 * <SDL.h> directly (real SDL2), NOT the SDL3->SDL2 shim, to avoid the
 * SDL_RenderDebugText macro rewriting our own definition.
 */
